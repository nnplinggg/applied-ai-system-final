"""Reliability harness: python -m eval.run_eval  -> prints table, writes eval/results.md."""
import os
import statistics

os.environ.setdefault("CONCIERGE_LOG", "logs/eval.log")

from src.concierge import build_agent  # noqa: E402

# (query, allowed statuses, allowed top-song genres or None, what is being checked)
CASES = [
    ("quiet music for studying and reading", {"ok"}, {"lofi", "ambient"}, "typical request"),
    ("cozy rainy afternoon, calm and gentle", {"ok"}, {"lofi", "ambient", "jazz"}, "typical request"),
    ("high intensity gym workout", {"ok"}, {"pop", "edm", "rock", "metal"}, "typical request"),
    ("friday night dance party", {"ok"}, {"edm", "pop"}, "typical request"),
    ("romantic dinner date", {"ok", "low_confidence"}, {"r&b", "classical"}, "typical request"),
    ("workout music but I want metal", {"ok", "low_confidence"}, {"metal"}, "explicit genre override"),
    ("road trip with country nostalgia", {"ok"}, {"country", "folk"}, "typical request"),
    ("sad heartbreak songs but very high energy", {"low_confidence"}, None, "contradictory request -> human-in-the-loop"),
    ("zxqv plmk wrtb", {"needs_clarification"}, None, "gibberish -> asks for clarification"),
    ("vibes", {"needs_clarification", "low_confidence"}, None, "too vague"),
    ("", {"rejected"}, None, "empty input"),
    ("!!! 12345 ???", {"rejected"}, None, "non-text input"),
    ("study " * 100, {"rejected"}, None, "over-length input"),
]


def run():
    agent = build_agent()
    rows, confs = [], []
    for query, statuses, genres, what in CASES:
        try:
            r = agent.run(query)
            ok = r.status in statuses and (genres is None or (r.recs and r.recs[0].song["genre"] in genres))
            top = f"{r.recs[0].song['title']} ({r.recs[0].song['genre']})" if r.recs else "-"
            if r.recs:
                confs.append(r.confidence)
            rows.append((query.strip()[:40] or "(empty)", what, r.status, f"{r.confidence:.2f}", top, "PASS" if ok else "FAIL"))
        except Exception as e:  # a crash is a failed case, not a harness crash
            rows.append((query[:40], what, f"CRASH {type(e).__name__}", "-", "-", "FAIL"))
    passed = sum(r[-1] == "PASS" for r in rows)
    out = ["| Input | Checks | Status | Confidence | Top pick | Result |", "|---|---|---|---|---|---|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    out.append("")
    out.append(f"**{passed}/{len(rows)} passed.** Mean confidence on cases that returned recommendations: "
               f"{statistics.mean(confs):.2f} (n={len(confs)}).")
    return "\n".join(out), passed, len(rows)


if __name__ == "__main__":
    text, passed, total = run()
    print(text)
    with open("eval/results.md", "w", encoding="utf-8") as f:
        f.write("# Reliability evaluation\n\nGenerated by `python -m eval.run_eval`.\n\n" + text + "\n")
    raise SystemExit(0 if passed == total else 1)
